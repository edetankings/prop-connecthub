"""Generate a plain SQL artifact locally. Never connects to a database."""
from pathlib import Path
import re

base = Path(__file__).resolve().parent
installer = (base / 'install.psql').read_text(encoding='utf-8')
names = re.findall(r'^\\ir (.+)$', installer, re.M)
expected = ['00_preflight.sql', '01_schema.sql', '02_relationships.sql',
            '03_identity.sql', '04_guards.sql', '05_finance.sql',
            '06_workflows.sql', '07_security.sql', '08_integrations.sql', '09_seed.sql']
if names != expected:
    raise SystemExit('Installer order changed; review generator before proceeding.')
header = ('-- PROP-CONNECT independent baseline v1: SQL Editor installation artifact.\n'
          '-- Generated by build-sql-editor.py; numbered source files are unchanged.\n'
          '-- Run the ENTIRE file only after verifying the independent destination.\n'
          '-- No runtime rehearsal has passed. Running this file authorizes installation.\n'
          '-- On error, do not run fragments or remove guards; inspect destination state.\n'
          'BEGIN;\n'
          "SET LOCAL lock_timeout='5s';\n"
          "SET LOCAL statement_timeout='120s';\n")
combined = header
for name in names:
    source = (base / name).read_text(encoding='utf-8')
    combined += '\n-- BEGIN SOURCE: ' + name + '\n' + source
    if not source.endswith('\n'):
        combined += '\n'
    combined += '-- END SOURCE: ' + name + '\n'
combined += '\nCOMMIT;\n'
(base / 'install-sql-editor.sql').write_text(combined, encoding='utf-8', newline='\n')
print('Generated install-sql-editor.sql from exactly ten local SQL files; no SQL executed.')
