"""Offline TypeScript contract from reviewed baseline DDL, not live introspection.

Requires pglast 8.6 outside app dependencies. Live CLI generation remains required
before cutover; this contract does not certify the installed schema.
"""
import argparse
import sys
from pathlib import Path
import re
import json

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--parser-path')
args = parser.parse_args()
if args.parser_path:
    sys.path.insert(0, args.parser_path)
from pglast import ast, parse_sql

root = Path(__file__).resolve().parents[1]
base = root/'database/independent-baseline/v1'
target = root/'src/integrations/supabase/types.ts'
old = target.read_text(encoding='utf-8')
tables, enums, functions, relations, unique = {}, {}, {}, {}, {}
for source in sorted(base.glob('0[0-9]_*.sql')):
    for raw in parse_sql(source.read_text(encoding='utf-8')):
        n = raw.stmt
        if isinstance(n, ast.CreateEnumStmt):
            enums[n.typeName[-1].sval] = [x.sval for x in n.vals]
        if isinstance(n, ast.CreateStmt) and n.relation.schemaname == 'public':
            name = n.relation.relname
            tables[name] = [x for x in n.tableElts if isinstance(x, ast.ColumnDef)]
            constraints = [x for x in n.tableElts if isinstance(x, ast.Constraint)]
            unique[name] = [tuple(x.sval for x in c.keys or ()) for c in constraints
                            if c.contype.name in ('CONSTR_PRIMARY','CONSTR_UNIQUE')]
        if isinstance(n, ast.AlterTableStmt) and n.relation.schemaname == 'public':
            for cmd in n.cmds:
                c = cmd.def_
                if isinstance(c, ast.Constraint) and c.pktable and c.pktable.schemaname == 'public':
                    relations.setdefault(n.relation.relname, []).append(c)
        if isinstance(n, ast.CreateFunctionStmt) and n.funcname[0].sval in ('public','prop_connect_private'):
            functions['.'.join(x.sval for x in n.funcname)] = n

def ts(t):
    name = t.names[-1].sval
    if name in enums:
        result = 'Database["public"]["Enums"]["'+name+'"]'
    elif name in tables:
        result = 'Database["public"]["Tables"]["'+name+'"]["Row"]'
    elif name in ('int2','int4','int8','float4','float8','numeric','integer','bigint'):
        result = 'number'
    elif name in ('bool','boolean'):
        result = 'boolean'
    elif name in ('json','jsonb'):
        result = 'Json'
    elif name == 'void':
        result = 'undefined'
    elif name == 'trigger':
        result = 'never'
    elif name in ('text','uuid','varchar','bpchar','timestamptz','timestamp','date','time','interval'):
        result = 'string'
    else:
        raise ValueError('Review SQL type: '+name)
    return result + ('[]' if t.arrayBounds else '')

out = ['// Offline baseline contract generated by scripts/generate-baseline-types.py.',
       '// Not generated from the destination. Regenerate with the Supabase CLI before cutover.',
       'export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]',
       'export type Database = {', '  public: {', '    Tables: {']
for name, cols in sorted(tables.items()):
    out.append('      '+name+': {')
    for mode in ('Row','Insert','Update'):
        out.append('        '+mode+': {')
        for c in sorted(cols, key=lambda x: x.colname):
            kinds = {x.contype.name for x in c.constraints or ()}
            primary = (c.colname,) in unique[name] and c.colname == 'id'
            nullable = 'CONSTR_NOTNULL' not in kinds and not primary
            default = 'CONSTR_DEFAULT' in kinds
            optional = mode == 'Update' or (mode == 'Insert' and (nullable or default))
            out.append('          '+c.colname+('?' if optional else '')+': '+ts(c.typeName)+(' | null' if nullable else ''))
        out.append('        }')
    out.append('        Relationships: [')
    for c in relations.get(name, []):
        local = [x.sval for x in c.fk_attrs]
        out.append('          { foreignKeyName: '+json.dumps(c.conname)+'; columns: '+json.dumps(local)+
                   '; isOneToOne: '+str(tuple(local) in unique[name]).lower()+
                   '; referencedRelation: '+json.dumps(c.pktable.relname)+
                   '; referencedColumns: '+json.dumps([x.sval for x in c.pk_attrs])+' },')
    out += ['        ]','      }']
out += ['    }','    Views: {','      public_profiles: {','        Row: {']
for p in functions['prop_connect_private.public_agent_rows'].parameters:
    if p.mode.name == 'FUNC_PARAM_TABLE':
        out.append('          '+p.name+': '+ts(p.argType)+' | null')
out += ['        }','        Relationships: []','      }','    }','    Functions: {']
for name,n in sorted(functions.items()):
    if not name.startswith('public.') or n.returnType.names[-1].sval == 'trigger':
        continue
    inputs = [p for p in n.parameters or () if p.mode.name != 'FUNC_PARAM_TABLE']
    outputs = [p for p in n.parameters or () if p.mode.name == 'FUNC_PARAM_TABLE']
    args_ts = '{ '+ '; '.join(p.name+('?' if p.defexpr is not None else '')+': '+ts(p.argType) for p in inputs)+' }' if inputs else 'never'
    result = '{ '+ '; '.join(p.name+': '+ts(p.argType)+' | null' for p in outputs)+' }[]' if outputs else ts(n.returnType)
    out += ['      '+name.split('.')[1]+': { Args: '+args_ts+'; Returns: '+result+' }']
out += ['    }','    Enums: {']
for name,values in sorted(enums.items()):
    out.append('      '+name+': '+' | '.join(json.dumps(x) for x in values))
out += ['    }','    CompositeTypes: { [_ in never]: never }','  }','}','']
suffix = old[old.index('type DatabaseWithoutInternals'):]
target.write_text('\n'.join(out)+suffix, encoding='utf-8', newline='\n')
print('Generated offline contract: 30 tables, six enums; destination not contacted.')
